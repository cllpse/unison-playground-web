// Generates src/app/frame.css from the unison-components submodule's design tokens: the
// library's colors as Tailwind theme colors, and a safelist of the class names
// it builds at runtime (e.g. `bg-${color}-${shade}`), which Tailwind can't find
// by scanning the source. Runs before `dev` and `build`, so bumping the
// submodule keeps it in sync.
import { writeFileSync } from "node:fs"
import { COLORS } from "../unison-components/src/constants/colors"
import { UNITS, UNITS_TAILWIND } from "../unison-components/src/constants/units"

const units = Object.keys(UNITS) as (keyof typeof UNITS)[]
const spacing = [...new Set(units.map((unit) => UNITS_TAILWIND[unit] ?? unit))]
const radius = [...new Set(units.map((unit) => UNITS_TAILWIND[unit] ?? `[${UNITS[unit]}px]`))]

const theme: string[] = []
const colors: string[] = []
// Shadows embed a color: neutral-200 on white fills, otherwise the fill
// palette's 100 shade.
const shadowColors = new Set<string>([COLORS.neutral[200]])

for (const [name, value] of Object.entries(COLORS)) {
  if (typeof value === "string") {
    theme.push(`  --color-${name}: ${value};`)
    colors.push(name)
    continue
  }

  for (const [shade, hex] of Object.entries(value)) {
    theme.push(`  --color-${name}-${shade}: ${hex};`)
    colors.push(`${name}-${shade}`)
  }

  shadowColors.add(value[100])
}

const shadows = [...shadowColors].flatMap((color) =>
  [4, 16].map((blur) => `shadow-[0_4px_${blur}px_0_color-mix(in_oklab,${color},transparent)]`),
)

const css = [
  "/* Generated by scripts/generate-frame-css.ts from the unison-components submodule. Do not edit. */",
  "",
  '@source "../../unison-components/src";',
  "",
  "@theme {",
  ...theme,
  "}",
  "",
  `@source inline("{,hover:}{bg,text,outline}-{${colors.join(",")}}");`,
  `@source inline("group-hover:text-{${colors.join(",")}}");`,
  `@source inline("{p,px,py,pl,pr,pt,pb,gap,w,h}-{${spacing.join(",")}}");`,
  `@source inline("rounded{,-tl,-tr,-bl,-br}-{${radius.join(",")}}");`,
  ...shadows.map((shadow) => `@source inline("${shadow}");`),
  "",
].join("\n")

writeFileSync(new URL("../src/app/frame.css", import.meta.url), css)
